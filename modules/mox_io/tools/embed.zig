//! Host-side command for packing assets and generating an importable Zig module.

const std = @import("std");
const Pack = @import("pack.zig");

const Io = std.Io;

const usage =
    \\Usage: mox-io-embed <directory> (-o <image.lzfs> | --module <output-directory>)
    \\Options: --max-bytes <n> --max-entries <n> --help
    \\All files and empty directories are included. Symbolic links are rejected.
    \\Output must be outside the input directory.
    \\
;
const module_source =
    \\//! Generated by mox-io-embed.
    \\pub const image: []const u8 = @embedFile("assets.lzfs");
    \\
;

pub fn main(init: std.process.Init) void {
    run(init) catch |err| std.process.fatal("mox-io-embed: {t}", .{err});
}

fn run(init: std.process.Init) !void {
    const allocator = init.arena.allocator();
    const args = try init.minimal.args.toSlice(allocator);
    var input: ?[]const u8 = null;
    var output: ?[]const u8 = null;
    var module = false;
    var options: Pack.Options = .{};
    var index: usize = 1;
    while (index < args.len) : (index += 1) {
        const arg = args[index];
        if (std.mem.eql(u8, arg, "--help") or std.mem.eql(u8, arg, "-h")) {
            try Io.File.stdout().writeStreamingAll(init.io, usage);
            return;
        } else if (std.mem.eql(u8, arg, "-o") or std.mem.eql(u8, arg, "--module")) {
            if (output != null or index + 1 == args.len) return error.InvalidArguments;
            module = std.mem.eql(u8, arg, "--module");
            index += 1;
            output = args[index];
        } else if (std.mem.eql(u8, arg, "--max-bytes")) {
            index += 1;
            if (index == args.len) return error.InvalidArguments;
            options.max_bytes = try std.fmt.parseInt(u64, args[index], 10);
        } else if (std.mem.eql(u8, arg, "--max-entries")) {
            index += 1;
            if (index == args.len) return error.InvalidArguments;
            options.max_entries = try std.fmt.parseInt(u32, args[index], 10);
        } else if (arg.len != 0 and arg[0] != '-' and input == null) {
            input = arg;
        } else return error.InvalidArguments;
    }
    if (input == null or output == null) {
        try Io.File.stderr().writeStreamingAll(init.io, usage);
        return error.InvalidArguments;
    }

    const io = init.io;
    const cwd = try std.process.currentPathAlloc(io, allocator);
    const source_path = try std.fs.path.resolve(allocator, &.{ cwd, input.? });
    const output_path = try std.fs.path.resolve(allocator, &.{ cwd, output.? });
    // Avoid including a previous output image in the next build.
    const relative = try std.fs.path.relativeAlloc(allocator, cwd, init.environ_map, source_path, output_path);
    if (relative.len == 0 or (!std.mem.eql(u8, relative, "..") and !std.mem.startsWith(u8, relative, ".." ++ std.fs.path.sep_str) and !std.fs.path.isAbsolute(relative))) return error.OutputInsideInput;
    const directory = try Io.Dir.cwd().openDir(io, input.?, .{ .iterate = true, .follow_symlinks = false });
    defer directory.close(io);
    var plan = try Pack.init(init.gpa, io, directory, options);
    defer plan.deinit();
    if (module) {
        const destination = try Io.Dir.cwd().createDirPathOpen(io, output.?, .{});
        defer destination.close(io);
        try writeImage(plan, io, directory, destination, "assets.lzfs");
        var source = try destination.createFileAtomic(io, "root.zig", .{ .replace = true });
        defer source.deinit(io);
        try source.file.writeStreamingAll(io, module_source);
        try source.replace(io);
    } else try writeImage(plan, io, directory, .cwd(), output.?);
}

fn writeImage(plan: Pack, io: Io, directory: Io.Dir, destination: Io.Dir, name: []const u8) !void {
    var output = try destination.createFileAtomic(io, name, .{ .replace = true, .make_path = true });
    defer output.deinit(io);
    var buffer: [64 * 1024]u8 = undefined;
    var writer = output.file.writer(io, &buffer);
    try plan.write(io, directory, &writer.interface);
    try writer.interface.flush();
    try output.replace(io);
}
